"""Write results/SUMMARY.md: the key tables from every experiment, in Markdown."""
import csv
import glob
import os
import statistics as st

from common import RESULTS, log


def rows(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def F(x):
    return float(x) if x not in (None, "", "None") else None


def pct(x):
    return "–" if x is None or x != x else f"{100 * x:.1f}%"


out = ["# Results summary", "", "Generated by `experiments/make_summary.py` from the CSV files in this folder.", ""]

for trace in ("toolagent", "conversation"):
    p = os.path.join(RESULTS, f"e1_endurance_{trace}.csv")
    if not os.path.exists(p):
        continue
    out += [f"## E1 endurance arithmetic ({trace} day, Llama-3.1-70B)", "",
            "| Cell | Stacks | Budget TB/day | Share of write-all | Write-all life (y) | Residence at budget (h) |",
            "|---|---|---|---|---|---|"]
    for r in rows(p):
        if r["model"] == "Llama-3.1-70B":
            out.append(f"| {r['cell']} | {r['stacks_per_node']} | {F(r['budget_TB_per_day']):.1f} | {pct(F(r['budget_share_of_write_all']))} | "
                       f"{F(r['write_all_lifetime_years']):.2f} | {F(r['fifo_residence_h_at_budget']):.2f} |")
    out.append("")

for trace in ("toolagent", "conversation"):
    files = sorted(glob.glob(os.path.join(RESULTS, f"e3_days_*-*_{trace}.csv")))
    if not files:
        continue
    R = [r for p in files for r in rows(p)]
    ref = os.path.join(RESULTS, f"e3_static_0-1_{trace}.csv")
    if os.path.exists(ref):   # refined constant price (e3_static.py) replaces the coarse one
        R = [r for r in R if not (r["policy"] == "static price (hindsight)" and r["seeds"] == "0-1")] + rows(ref)
    pairs = sorted({r["seeds"] for r in R})
    out += [f"## E3 two-day results, {trace} (day 2; mean over day pairs {', '.join(pairs)})", "",
            "| Policy | Budget | Written / budget | Kept (share of write-all flash savings) | Max lead (share of a day's budget) |",
            "|---|---|---|---|---|"]
    keys = []
    for r in R:
        k = (r["policy"], r["budget_share"])
        if k not in keys and "(sweep)" not in r["policy"] and "(extra)" not in r["policy"]:
            keys.append(k)
    for pol, b in keys:
        sel = [r for r in R if r["policy"] == pol and r["budget_share"] == b]
        val = st.mean(F(r["value_share"]) for r in sel)
        if b:
            wob = st.mean(F(r["written_over_budget"]) for r in sel)
            ahead = max(F(r["max_ahead_share_of_daily_budget"]) for r in sel)
            out.append(f"| {pol} | {pct(F(b))} | {wob:.3f} | {pct(val)} | {pct(ahead)} |")
        else:
            w = st.mean(F(r["written_share"]) for r in sel)
            out.append(f"| {pol} | none (writes {pct(w)} of write-all) | – | {pct(val)} | – |")
    out.append("")
    # equal bytes, day pair 0-1: interpolate each policy's sweep at exactly the budget's bytes
    sw = {p: sorted((F(r["written_share"]), F(r["value_share"])) for r in R if r["policy"] == p and r["seeds"] == "0-1")
          for p in ("ROAR (sweep)", "period-quota k=2 (sweep)", "stepwise-quota (sweep)", "oracle (sweep)")}
    if all(sw.values()):
        def at(pts, x):
            pts = [(0.0, 0.0)] + pts
            if x >= pts[-1][0]:
                return pts[-1][1]
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                if x0 <= x <= x1:
                    return y0 + (y1 - y0) * (x - x0) / (x1 - x0) if x1 > x0 else y1
        out += [f"Equal bytes, day pair 0-1 ({trace}): value at exactly the stated share of write-all bytes, interpolated along "
                "each policy's budget sweep.", "",
                "| Bytes written | ROAR | Period quota k=2 | Stepwise quota | Oracle |", "|---|---|---|---|---|"]
        for b in (0.05, 0.10, 0.20):
            out.append(f"| {pct(b)} | " + " | ".join(pct(at(sw[p], b)) for p in sw) + " |")
        out.append("")

p = os.path.join(RESULTS, "e4_cell_modes_toolagent.csv")
if os.path.exists(p):
    out += ["## E4 cell modes (tool-and-agent, day 2)", "",
            "| Stacks | Configuration | Policy | Budget share | Written / budget | GPU-h/day saved by flash | Same, unlimited capacity | FIFO discards (2 days) |",
            "|---|---|---|---|---|---|---|---|"]
    for r in rows(p):
        unl = F(r.get("flash_saved_gpu_h_unlimited_capacity"))
        out.append(f"| {r['stacks']} | {r['config']} | {r['policy']} | {pct(F(r['budget_share']))} | {F(r['written_over_budget']):.2f} | "
                   f"{F(r['flash_saved_gpu_h_per_day']):.2f} | {('–' if unl is None else f'{unl:.2f}')} | {r['fifo_discards_two_days']} |")
    out.append("")

p = os.path.join(RESULTS, "e5_sensitivity_toolagent.csv")
if os.path.exists(p):
    out += ["## E5 sensitivity (tool-and-agent, 10% budget, day 2)", "",
            "| Study | Variant | Kept | Written / budget | Max lead (intervals) | Bound (intervals) |", "|---|---|---|---|---|---|"]
    for r in rows(p):
        bnd = F(r["bound_intervals"])
        out.append(f"| {r['study']} | {r['variant']} | {pct(F(r['value_share']))} | {F(r['written_over_budget']):.3f} | "
                   f"{F(r['max_ahead_intervals']):.0f} | {('–' if bnd is None else f'{bnd:.0f}')} |")
    out.append("")

T = []
for name in ("e5d_tune_arxiv_high.csv", "e5d_tune_arxiv_low.csv", "e5e_slower_gain_arxiv.csv"):
    p = os.path.join(RESULTS, name)
    if os.path.exists(p):
        T += rows(p)
if T:
    out += ["## Tuning (arXiv hour only; warm-up gain 0.05 for 6 h, then eta)", "",
            "| Budget | eta | Band | Kept | Written / budget | Max lead (days of budget) | Bound (intervals) |", "|---|---|---|---|---|---|---|"]
    for r in T:
        if r.get("policy") != "ROAR":
            out.append(f"| (admit-on-3 writes {pct(F(r['written_share']))}) | – | – | {pct(F(r['value_share']))} | – | – | – |")
            continue
        out.append(f"| {pct(F(r['budget_share']))} | {r['eta']} | {r['soft']} | {pct(F(r['value_share']))} | {F(r['written_over_budget']):.3f} | "
                   f"{F(r['max_ahead_share_of_daily_budget']):.3f} | {F(r['bound_intervals']):.0f} |")
    out.append("")

p = os.path.join(RESULTS, "check_handover_conversation.json")
if os.path.exists(p):
    import json
    H = json.load(open(p))
    out += ["## Where ROAR's lead comes from (conversation, day pair 0-1, 10% budget)", "",
            f"Price at the end of the fast phase (06:00, day 1): {H['price_at_handover']:.4g}; lead then: "
            f"{H['lead_at_handover']:+.3f} day of budget. Day-2 price range: {H['day2_price_min']:.3g} to {H['day2_price_max']:.3g}.", "",
            "| Hour since start | Price | Lead (days of budget) |", "|---|---|---|"]
    for x in H["samples"]:
        out.append(f"| {x['hour']:.0f} | {x['price']:.4g} | {x['lead_days_of_budget']:+.3f} |")
    out.append("")

with open(os.path.join(RESULTS, "SUMMARY.md"), "w") as f:
    f.write("\n".join(out) + "\n")
log("wrote results/SUMMARY.md")
